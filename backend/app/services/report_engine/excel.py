"""Write-only Excel export for report-builder results."""

import io
from datetime import date, datetime
from typing import Any

from openpyxl import Workbook


HEADERS = (
    "Label",
    "Sublabel",
    "Achievement",
    "Target",
    "Adjusted target",
    "Percent applied",
    "Proration factor",
    "Percentage",
    "Remaining",
    "Status",
)


def _safe_cell(value: Any) -> Any:
    if isinstance(value, str) and value.startswith(("=", "+", "-", "@", "\t", "\r")):
        return f"'{value}"
    return value


def _display_date(value: str | date | datetime | None) -> str:
    if value is None:
        return ""
    parsed = value if isinstance(value, (date, datetime)) else date.fromisoformat(value)
    if isinstance(parsed, datetime):
        parsed = parsed.date()
    return parsed.strftime("%d %b %Y")


def _value(row: Any, key: str) -> Any:
    return row.get(key) if isinstance(row, dict) else getattr(row, key, None)


def build_report_workbook(
    *,
    meta: dict,
    rows: list[dict],
    summary: dict,
    warnings: list[dict],
    filters_text: str,
    generated_by: str,
    generated_at: datetime | None = None,
) -> bytes:
    workbook = Workbook(write_only=True)
    sheet = workbook.create_sheet("Report")

    metric_label = meta.get("metric_label_en") or meta.get("metric", "")
    dimension_label = meta.get("dimension_label_en") or meta.get("group_by", "")
    period = (
        f"{_display_date(meta.get('date_from'))} – "
        f"{_display_date(meta.get('date_to'))}"
    )
    target_description = meta.get("target_source", "")
    if meta.get("target_value") is not None:
        target_description = f"{target_description}: {meta['target_value']}"

    header_rows = (
        ("Metric", metric_label),
        ("Dimension", dimension_label),
        ("Period", period),
        ("Target source", target_description),
        ("Summary achievement", summary.get("achievement")),
        ("Summary target", summary.get("target")),
        ("Filters", filters_text or "None"),
        ("Generated by", generated_by),
        ("Generated at", generated_at),
    )
    for row in header_rows:
        sheet.append([_safe_cell(value) for value in row])

    for warning in warnings:
        sheet.append([
            "Warning",
            _safe_cell(warning.get("code", "")),
            _safe_cell(warning.get("message", "")),
            warning.get("count"),
        ])

    sheet.append([])
    sheet.append([_safe_cell(header) for header in HEADERS])
    for row in rows:
        sheet.append([
            _safe_cell(_value(row, "label")),
            _safe_cell(_value(row, "sublabel")),
            _value(row, "achievement"),
            _value(row, "target"),
            _value(row, "adjusted_target"),
            _value(row, "percent_applied"),
            _value(row, "proration_factor"),
            _value(row, "percentage"),
            _value(row, "remaining"),
            _safe_cell(_value(row, "status")),
        ])

    output = io.BytesIO()
    workbook.save(output)
    return output.getvalue()
